if __name__ == "__main__":
    print("── Perplexity Inversion Self-Test ───────────────────────")
    passed = failed = 0

    def check(name, condition, detail=""):
        global passed, failed
        marker = "[PASS]" if condition else "[FAIL]"
        print(f"  {marker} {name}{' — ' + detail if detail else ''}")
        if condition:
            passed += 1
        else:
            failed += 1

    # Synthetic test: mock the PPL computation directly
    # Healthy: G0 PPL ≈ Gk PPL → ratio ≈ 1.0
    # Collapsed: Gk PPL << G0 PPL → ratio >> 1.0

    def _mock_result(ppl_g0_list, ppl_gk_list):
        valid = [(p0, pk) for p0, pk in zip(ppl_g0_list, ppl_gk_list)
                 if math.isfinite(p0) and math.isfinite(pk) and pk > 0]
        ratios = [p0/pk for p0, pk in valid]
        return {
            "ppl_under_g0": np.mean([v[0] for v in valid]),
            "ppl_under_gk": np.mean([v[1] for v in valid]),
            "perplexity_inversion_ratio": float(np.mean(ratios)),
            "n_valid_samples": len(valid),
        }

    rng = np.random.default_rng(42)
    # Healthy: both models score similarly
    g0_healthy = rng.normal(45, 5, 100).tolist()
    gk_healthy = rng.normal(44, 5, 100).tolist()
    r_h = _mock_result(g0_healthy, gk_healthy)

    # Collapsed: Gk is very confident (low PPL), G0 finds outputs strange (high PPL)
    g0_collapsed = rng.normal(70, 10, 100).tolist()
    gk_collapsed = rng.normal(20, 3, 100).tolist()
    r_c = _mock_result(g0_collapsed, gk_collapsed)

    check("Healthy ratio ≈ 1.0",
          0.8 <= r_h["perplexity_inversion_ratio"] <= 1.3,
          f"{r_h['perplexity_inversion_ratio']:.4f}")
    check("Collapsed ratio > Healthy ratio",
          r_c["perplexity_inversion_ratio"] > r_h["perplexity_inversion_ratio"],
          f"{r_c['perplexity_inversion_ratio']:.4f} > {r_h['perplexity_inversion_ratio']:.4f}")
    check("Collapsed ratio > 1.5",
          r_c["perplexity_inversion_ratio"] > 1.5,
          f"{r_c['perplexity_inversion_ratio']:.4f}")

    print(f"\n  {'✓ PERPLEXITY INVERSION SELF-TEST PASSED' if failed == 0 else '✗ PERPLEXITY INVERSION SELF-TEST FAILED'} "
          f"({passed}/{passed+failed})")
